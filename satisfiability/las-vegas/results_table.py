"""The markdown table read off `results.json`, so the two cannot disagree.

`measure.py` writes the JSON and calls this for `results.md`; nothing here runs
a solver or reads a file, it only renders what it is handed.
"""
from solver_runs import FINDS_ONLY


def cell(block):
    """One solver's cell: `finished / seeds, mean over the finished` for a
    distribution, which is `[nawrocki2021]`'s measure, and `seconds verdict` for
    a deterministic run. The median over all seeds stays in the JSON."""
    if "finished_within_cap" in block:
        mean = block.get("mean_seconds_of_finished")
        shown_mean = f"mean {mean:.2f} s" if mean is not None else f"none within {block['cap_seconds']} s"
        return f"{block['finished_within_cap']}/{block['of']}, {shown_mean}"
    return f"{block['seconds']:.3f} s {block['verdict']}"


def solver_columns(rows):
    """Every solver any row names, the complete ones first."""
    return sorted({name for row in rows for name in row["solvers"]},
                  key=lambda name: (name in FINDS_ONLY, name))


def rendered(rows, first_columns, first_of):
    """A table whose leading columns come from `first_of(row)` and whose
    remaining columns are one per solver."""
    names = solver_columns(rows)
    lines = ["| " + " | ".join(first_columns + names) + " |",
             "|" + "---|" * (len(first_columns) + len(names))]
    for row in rows:
        cells = [cell(row["solvers"][name]) if name in row["solvers"] else "" for name in names]
        lines.append("| " + " | ".join(first_of(row) + cells) + " |")
    return lines


def table(document):
    lines = ["# What a solver that can only find costs, against kissat", "",
             "Generated by `measure.py` from `results.json`. A finds-only cell is "
             "`seeds finished within the cap / seeds, mean seconds over those that did`, "
             "which is the measure of `[nawrocki2021]`; the median over all seeds, above the "
             "cap when half or more hit it, is in the JSON. A kissat cell on a fixture is the "
             "fastest of three; on a challenge instance it is one run, in the same "
             "`finished / runs` shape. The provenance block in the JSON names the commit, "
             "the solvers, the caps and the job count."]
    if document.get("fixtures"):
        lines += ["", "## Fixtures, through `decide-rank-by-sat --plain-cnf`", ""]
        lines += rendered(document["fixtures"], ["fixture", "find", "ordering"],
                          lambda row: [f"`{row['fixture']}`", str(row["target"]),
                                       "on" if row["break_symmetry"] else "off"])
    if document.get("challenges"):
        lines += ["", "## Heule's challenge 1, run directly, every find checked against "
                  "the clauses", ""]
        lines += rendered(document["challenges"], ["instance"],
                          lambda row: [f"`{row['instance']}`"])
    return "\n".join(lines) + "\n"
